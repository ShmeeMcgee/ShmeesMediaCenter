#!/usr/bin/env python3
"""Writes probes.h: one function a vector or cache instruction FFmpeg's PowerPC code uses, each running that exact
instruction word as FFmpeg's compiled code has it, from objdump -d of FFmpeg's ppc objects (prefixed by file name)."""
import re, sys
dis = open(sys.argv[1]).read().splitlines()
pat = re.compile(r'^(\S+)\s+[0-9a-f]+:\s+([0-9a-f]{2}) ([0-9a-f]{2}) ([0-9a-f]{2}) ([0-9a-f]{2})\s+(\S+)\s*(.*)$')
first = {}
users = {}
for line in dis:
    m = pat.match(line.strip())
    if not m:
        continue
    obj, b0, b1, b2, b3, mnem, ops = m.groups()
    word = int(b0 + b1 + b2 + b3, 16)
    op = word >> 26
    is_vec = op == 4
    is_mem = op == 31 and re.match(r'^(lv|stv|dcb)', mnem)
    if not (is_vec or is_mem):
        continue
    users.setdefault(mnem, set()).add(obj.replace('.o', ''))
    first.setdefault(mnem, (word, ops, is_mem))
# Most likely to be missing on Xenon: the integer multiply, multiply-sum and sum-across ops, and the 128-byte cache
# line ops. They go last, so one run clears everything else first.
suspect = re.compile(r'^(vmul|vmsum|vsum|vmladd|vmhadd|vmhradd|dcbzl|dcbtct|dcbz$)')
controls = ['lvx', 'stvx', 'vperm', 'vor', 'vmr']
names = sorted(first)
order = [n for n in controls if n in first] + [n for n in names if n not in controls and not suspect.match(n)] + \
        [n for n in names if suspect.match(n) and n not in controls]
vregs = ','.join('"v%d"' % i for i in range(32))
out = ['// Generated by gen_probes.py from FFmpeg 9.0.2\'s PowerPC objects. Do not edit.', '']
for i, n in enumerate(order):
    word, ops, is_mem = first[n]
    fn = 'probe_%d' % i
    if is_mem:
        # The same instruction with its address in r11 (RA 0, RB 11): a 128-byte-aligned buffer of 256 bytes.
        w = (word & ~((31 << 16) | (31 << 11))) | (11 << 11)
        out.append('static void %s(void *buffer)\n{\n\t__asm__ volatile("mr 11,%%0\\n\\t.long 0x%08X" : : "r"(buffer) : "r11", %s, "memory");\n}' % (fn, w, vregs))
    else:
        out.append('static void %s(void *buffer)\n{\n\t(void)buffer;\n\t__asm__ volatile(".long 0x%08X" : : : %s);\n}' % (fn, word, vregs))
out.append('')
out.append('static const Probe PROBES[] = {')
for i, n in enumerate(order):
    word, ops, is_mem = first[n]
    out.append('\t{ "%s", "%s", "%s", %d, probe_%d },' % (n, ops, ' '.join(sorted(users[n])), 1 if suspect.match(n) else 0, i))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(order), 'probes;', sum(1 for n in order if suspect.match(n)), 'suspects:', ' '.join(n for n in order if suspect.match(n)))
